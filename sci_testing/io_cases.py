"""Independent SciPy 1.18.1 / NumPy 2.5.4 comparisons for public ``sci::io``.

Inputs are copied verbatim into each case from the pinned, independently
generated ``sci/tests/fixtures/io_inputs.csv``. The source is generated by
``sci/tests/scipy/generate_io.py`` using public SciPy writers and explicitly
specified Matrix Market text. This module never runs or consults Sci Rust to
construct the expected results. All observations are finite numeric vectors;
nonfinite values and signed zero have explicit tags.

The file writers are compared by reading their results back with the Rust
reader. A separate cross-language consumer of Rust-produced files would be
needed to prove SciPy can decode their actual byte streams.
"""

import csv
from functools import lru_cache
import io
import math
from pathlib import Path
import struct
import warnings
import zlib

import numpy as np
import scipy
from scipy import io as sio, sparse

from . import SCI

SCIPY_VERSION = '1.18.1'
NUMPY_VERSION = '2.5.4'

FORMATS = {'array': 0, 'coordinate': 1}
FIELDS = {'real': 0, 'integer': 1, 'pattern': 2}
SYMMETRIES = {'general': 0, 'symmetric': 1, 'skew-symmetric': 2, 'hermitian': 3}
DTYPES = {
    'int8': 1, 'uint8': 2, 'int16': 3, 'uint16': 4,
    'int32': 5, 'uint32': 6, 'int64': 7, 'uint64': 8,
    'float32': 9, 'float64': 10,
}
CLASSES = {
    'double': 1, 'single': 2, 'int8': 3, 'uint8': 4,
    'int16': 5, 'uint16': 6, 'int32': 7, 'uint32': 8,
    'int64': 9, 'uint64': 10,
}
APIS = tuple(
    f'io.{family}.{function}'
    for family, methods in (
        ('matrix_market', ('mminfo', 'mmread', 'mmwrite')),
        ('wavfile', ('read', 'write', 'signal')),
        ('matlab', ('matfile_version', 'whosmat', 'loadmat', 'savemat')),
    )
    for function in methods
)


def _versions():
    if (scipy.__version__, np.__version__) != (SCIPY_VERSION, NUMPY_VERSION):
        raise RuntimeError('I/O references require scipy==1.18.1 and numpy==2.5.4')


@lru_cache(maxsize=1)
def _inputs():
    path = SCI / 'tests/fixtures/io_inputs.csv'
    with path.open(newline='') as stream:
        return tuple(csv.DictReader(stream))


def _case(api, record, operation='success', **options):
    suffix = f'-{options["channel"]}' if 'channel' in options else ''
    suffix += '-compressed' if options.get('compressed') else ''
    args = dict(io_case=True, operation=operation, payload_hex=record['hex'], **options)
    return dict(id=f'{api}/{record["id"]}{suffix}-{operation}', api=api,
                group='pinned SciPy 1.18.1 fixture; source bytes stored in args', args=args)


def cases(count, seed, apis=None):
    """Generate bounded, stable per-API inputs; ``seed`` is reserved for sweeps.

    All established fixtures are included at the production count (1000).
    Smaller calls reduce the number of MATLAB variants while keeping each
    public function and its essential format profiles represented.
    """
    del seed
    selected = set(APIS if apis is None else apis)
    rows = _inputs()
    matrix = [r for r in rows if r['format'] == 'market']
    audio = [r for r in rows if r['format'] == 'wav']
    matlab = [r for r in rows if r['format'] == 'matlab']
    # Each MATLAB dtype has plain, big-endian, compressed and big/compressed
    # variants. A full production run includes all; small tests use a prefix.
    matlab = matlab[:max(4, min(len(matlab), count))]
    for r in matrix:
        for name in ('mminfo', 'mmread', 'mmwrite'):
            api = f'io.matrix_market.{name}'
            if api in selected and not (r['id'] == 'empty_dense' and name != 'mminfo'):
                # SciPy's mmread 1.18.1 crashes on the empty_dense fixture.
                yield _case(api, r)
    for r in audio:
        for name in ('read', 'write', 'signal'):
            api = f'io.wavfile.{name}'
            if api not in selected:
                continue
            if name != 'signal':
                yield _case(api, r)
            else:
                width = struct.unpack_from('<H', bytes.fromhex(r['hex']), 22)[0]
                for channel in range(width):
                    yield _case(api, r, channel=channel)
                yield _case(api, r, operation='reject', channel=width)
    for r in matlab:
        for name in ('matfile_version', 'whosmat', 'loadmat', 'savemat'):
            api = f'io.matlab.{name}'
            if api not in selected:
                continue
            if name == 'savemat':
                for compressed in (False, True):
                    yield _case(api, r, compressed=compressed)
            else:
                yield _case(api, r)
    # These malformed records are rejected by both the public SciPy and Rust
    # readers. Unsupported but valid formats are intentionally excluded: SciPy
    # can read them while Sci deliberately exposes a smaller file domain.
    for r in rows:
        if r['id'] == 'zlib_corrupt':
            for name in ('whosmat', 'loadmat'):
                api = f'io.matlab.{name}'
                if api in selected:
                    yield _case(api, r, operation='reject')
        if r['id'] == 'mulaw_unsupported':
            api = 'io.wavfile.read'
            if api in selected:
                yield _case(api, r, operation='reject')
    for name in ('mminfo', 'mmread'):
        api = f'io.matrix_market.{name}'
        if api in selected:
            invalid = {'id': 'invalid-header', 'hex': b'%%MatrixMarket vector array real general\n2 2\n'.hex()}
            yield _case(api, invalid, operation='reject')


def _tag(value, *, signed_zero=True):
    v = float(value)
    if math.isnan(v):
        return [2., 0., 0.]
    if math.isinf(v):
        return [math.copysign(1., v), 0., 0.]
    return [0., v, -1. if signed_zero and v == 0. and math.copysign(1., v) < 0 else 1.]


def _numbers(values, *, signed_zero=True):
    return [part for x in values for part in _tag(x, signed_zero=signed_zero)]


def _numeric(values):
    arr = np.asarray(values)
    kind = arr.dtype.name
    result = [float(DTYPES[kind]), float(arr.size)]
    for value in arr.ravel(order='F'):
        if kind in ('int64', 'uint64'):
            bits = int(value) & 0xffffffffffffffff
            result.extend(_numbers((bits >> 32, bits & 0xffffffff)))
        else:
            result.extend(_tag(value))
    return result


def _market_matrix(value):
    is_sparse = sparse.issparse(value)
    dense = value.toarray() if is_sparse else np.asarray(value)
    return [float(is_sparse), *map(float, dense.shape),
            *_numbers(dense.ravel(), signed_zero=False)]


def _market_info(data):
    rows, cols, entries, fmt, field, symmetry = sio.mminfo(io.BytesIO(data))
    return [float(rows), float(cols), float(entries),
            float(FORMATS[fmt]), float(FIELDS[field]), float(SYMMETRIES[symmetry])]


def _wav(data):
    rate, samples = sio.wavfile.read(io.BytesIO(data))
    channels = samples.shape[1] if samples.ndim == 2 else 1
    pos = data.index(b'fmt ') + 4
    bits = struct.unpack_from('<H', data, pos + 18)[0]
    return [float(rate), float(channels), float(bits), *_numeric(samples.ravel())]


def _wav_signal(data, channel):
    _, values = sio.wavfile.read(io.BytesIO(data))
    channels = 1 if values.ndim == 1 else values.shape[1]
    if channel >= channels:
        raise ValueError('WAV channel out of range')
    sample = values if channels == 1 else values[:, channel]
    sig = sample.astype(np.float64)
    if sample.dtype.name == 'uint8':
        sig = (sig - 128.) / 128.
    elif sample.dtype.name == 'int16':
        sig /= 32768.
    elif sample.dtype.name == 'int32':
        sig /= 2147483648.
    return [float(sig.size), *_numbers(sig)]


def _mat_metadata(data):
    info = sio.whosmat(io.BytesIO(data))
    variables = sio.loadmat(io.BytesIO(data))
    result = [float(len(info))]
    for name, shape, cls in info:
        dtype_complex = np.iscomplexobj(variables[name])
        result.extend([float(len(name)), *map(float, name.encode('ascii')),
                       float(len(shape)), *map(float, shape),
                       float(CLASSES[cls]), float(dtype_complex)])
    return result


def _mat_values(data):
    variables = sio.loadmat(io.BytesIO(data))
    names = sorted(name for name in variables if not name.startswith('__'))
    result = [float(len(names))]
    for name in names:
        arr = np.asarray(variables[name])
        result.extend([float(len(name)), *map(float, name.encode('ascii')),
                       float(arr.ndim), *map(float, arr.shape),
                       float(np.iscomplexobj(arr))])
        result.extend(_numeric(arr.real))
        if np.iscomplexobj(arr):
            result.extend(_numeric(arr.imag))
    return result


def _read_reference(api, data, args):
    if api == 'io.matrix_market.mminfo':
        return _market_info(data)
    if api == 'io.matrix_market.mmread':
        return _market_matrix(sio.mmread(io.BytesIO(data), spmatrix=False))
    if api == 'io.matrix_market.mmwrite':
        a = sio.mmread(io.BytesIO(data), spmatrix=False)
        with io.BytesIO() as out:
            sio.mmwrite(out, a)
            out.seek(0)
            return _market_matrix(sio.mmread(out, spmatrix=False))
    if api == 'io.wavfile.read':
        return _wav(data)
    if api == 'io.wavfile.signal':
        return _wav_signal(data, args['channel'])
    if api == 'io.wavfile.write':
        rate, sample = sio.wavfile.read(io.BytesIO(data))
        # SciPy reads 24-bit PCM as left-aligned int32 but its public writer
        # serializes that dtype as 32-bit PCM. Sci's writer keeps the original
        # 24-bit encoding, so compare its roundtrip with SciPy's *read* of the
        # original 24-bit source rather than claiming equivalent writer bits.
        if _wav(data)[2] == 24.:
            return _wav(data)
        out = io.BytesIO()
        sio.wavfile.write(out, rate, sample)
        return _wav(out.getvalue())
    if api == 'io.matlab.matfile_version':
        return list(map(float, sio.matlab.matfile_version(io.BytesIO(data))))
    if api == 'io.matlab.whosmat':
        return _mat_metadata(data)
    if api == 'io.matlab.loadmat':
        return _mat_values(data)
    if api == 'io.matlab.savemat':
        variables = sio.loadmat(io.BytesIO(data))
        items = {key: value for key, value in variables.items() if not key.startswith('__')}
        out = io.BytesIO()
        sio.savemat(out, items, do_compression=args['compressed'])
        return _mat_values(out.getvalue())
    raise ValueError(f'unknown Sci I/O API {api}')


def reference(case):
    """Finite numeric reference from public SciPy I/O APIs and NumPy scaling."""
    _versions()
    args = case['args']
    data = bytes.fromhex(args['payload_hex'])
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        if args['operation'] == 'reject':
            try:
                _read_reference(case['api'], data, args)
            except (ValueError, TypeError, OSError, EOFError, RuntimeError, zlib.error):
                return [1.]
            return [0.]
        return _read_reference(case['api'], data, args)
