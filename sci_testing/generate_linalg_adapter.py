"""Reuse linalg's observable comparisons, retaining its independent invariants.

Macro collectors replace comparisons against CSV fields with measurements.
Comparisons against mathematical identities still execute normally. No expected
value is used to construct a Sci result. Nonunique bases use the same projectors,
reconstructions, ordered eigenvalues and residuals as the established Sci tests.
"""
from .rust_source import formatted
import re
from .api_registry import SCI

from . import ROOT


def generated():
    text=(SCI/'tests/linalg.rs').read_text()
    prefix=text[:text.index('fn check_scipy_references')]
    prefix=prefix.replace('mod common;', 'use crate::common;')
    prefix=prefix.replace('fn check_vector(', 'fn check_vector_plain(').replace('fn check_matrix(', 'fn check_matrix_plain(').replace('fn ccheck(', 'fn ccheck_plain(')
    start=text.index('        let a = || matrix(c[2]);')
    end=text.index('\n    }\n    assert_eq!(covered.len(), 105);',start)
    body=text[start:end]
    # ID skeletons can differ. Measure spectral residual and rank explicitly.
    first=body.index('                let expected = matrix(e[1]);')
    last=body.index('                assert_eq!(f.rank, e[2].parse().unwrap());',first)
    body=body[:first]+'''                let residual = l::interpolative::estimate_spectral_norm_diff(&convert_matrix(&a()), &convert_matrix(&actual)).unwrap();
                emit(residual);
'''+body[last:]
    body=body.replace('assert_eq!(t.prefix.to_string(), e[1]);','assert_eq!(t.prefix.to_string(), e[1].to_string());')
    body=body.replace('assert_eq!(t.dtype, "f64");','emit(t.dtype.to_string());')
    source=prefix+'\npub fn run(c: &[&str]) -> Vec<f64> {\nlet e=["";5];\nlet convert_matrix=|a: &[Vec<f64>]| a.to_vec();\nlet convert_vector=|a: &[f64]| a.to_vec();\nOUTPUT.with(|o|o.borrow_mut().clear());\n'+body+'\nOUTPUT.with(|o|o.borrow().clone())\n}\n'
    for name in ['check_vector','check_matrix','finite_close','ccheck']:
        source=re.sub(r'\b'+name+r'\(',name+'!(',source)
    return HEADER+'\n'+source


HEADER=r'''// Generated by generate_linalg_adapter.py from the pinned Sci test dispatcher.
#![allow(dead_code, unused_imports)]
use crate::numeric::Numbers;
use std::cell::RefCell;
thread_local! { static OUTPUT: RefCell<Vec<f64>> = const { RefCell::new(Vec::new()) }; }
fn emit<T: Numbers>(value: T) { OUTPUT.with(|o|o.borrow_mut().extend(value.numbers().unwrap())); }
fn same<T: PartialEq + std::fmt::Debug>(a: T,b: T) { std::assert_eq!(a,b); }
fn oracle(expression: &str) -> bool {
    let s: String=expression.chars().filter(|c|!c.is_whitespace()).collect();
    ["e[","expected[","vector(re)","vector(im)"].iter().any(|part|s.contains(part))
}
macro_rules! check_vector {
    ($a:expr,$b:expr $(,)?) => { if oracle(stringify!($b)) { emit($a); } else { check_vector_plain($a,$b); } };
}
macro_rules! check_matrix {
    ($a:expr,$b:expr $(,)?) => { if oracle(stringify!($b)) { emit($a); } else { check_matrix_plain($a,$b); } };
}
macro_rules! finite_close {
    ($a:expr,$b:expr,$rtol:expr,$atol:expr $(,)?) => { if oracle(stringify!($b)) { emit($a); } else { crate::common::finite_close($a,$b,$rtol,$atol); } };
}
macro_rules! ccheck {
    ($a:expr,$b:expr $(,)?) => { if oracle(stringify!($b)) { emit(complex_matrix($a).0); } else { ccheck_plain($a,$b); } };
}
macro_rules! assert_eq {
    ($a:expr,$b:expr $(,$rest:tt)*) => { if oracle(stringify!($b)) { emit($a); } else { same($a,$b); } };
}
'''

if __name__=='__main__':(ROOT/'src/linalg_adapter.rs').write_text(formatted(generated()))
