"""Regenerate one function at a time, keeping dense suites bounded in memory."""
from collections import defaultdict
from itertools import zip_longest
from functools import lru_cache
import hashlib
import json
from pathlib import Path
from .case_csv import (case_directory_digest, case_paths, csv_paths,
                       directory_digest, read_case_file, read_cases)

from . import ROOT


@lru_cache(maxsize=1)
def profiles():
    result=defaultdict(list)
    for case in read_cases(ROOT/'cases/recipes'):result[case['api']].append(case)
    return dict(result)


class CaseSet:
    def __init__(self,original,count,seed):
        from .explicit_cases import APIS
        self.original=defaultdict(list)
        for case in original:self.original[case['api']].append(case)
        self.count,self.seed=count,seed
        self.apis=sorted(set(self.original)|set(profiles())|set(APIS))

    def function(self,api):
        from .registered_cases import expanded_registered
        from .explicit_cases import cases
        batch=list(self.original.get(api,[]))
        if api in profiles():batch.extend(expanded_registered(self.count,self.seed,apis=[api]))
        batch.extend(cases(self.count,self.seed,apis=[api]))
        return sorted(batch,key=lambda c:c['id'])

    def for_module(self,module):
        for api in self.apis:
            if api.split('.')[0]==module:yield from self.function(api)

    def module_counts(self,module):
        from .explicit_cases import APIS
        names=[a for a in self.apis if a.split('.')[0]==module]
        count=0
        for api in names:
            count+=len(self.original.get(api,[]))
            if api in profiles():count+=len(profiles()[api])+2*self.count
            if api in APIS:count+=2*self.count
        return len(names),count

    def __iter__(self):
        for api in self.apis:yield from self.function(api)

    def __len__(self):
        from .explicit_cases import APIS
        return sum(map(len,self.original.values()))+sum(map(len,profiles().values()))+2*self.count*(len(profiles())+len(APIS))

    def __eq__(self,other):return all(a==b for a,b in zip_longest(self,other))


class CachedCaseSet:
    """Use a validated on-disk input snapshot, decoding only the requested API."""
    def __init__(self,directory,paths,counts,provenance=None):
        self.directory=Path(directory)
        self.paths=paths
        self.counts=counts
        self.provenance=provenance
        self.apis=sorted(name.removesuffix('.csv').replace('/','.') for name in paths)
        self._api=None
        self._batch=None

    def function(self,api):
        if api!=self._api:
            module,name=api.rsplit('.',1)
            logical=f'{module}/{name}.csv'
            batch=read_case_file(self.paths[logical],logical)
            if len(batch)!=self.counts[logical] or any(not c['id'].startswith(api+'/') for c in batch):
                raise ValueError(f'Stale case CSV: {logical}')
            self._api,self._batch=api,batch
        return list(self._batch)

    def for_module(self,module):
        for api in self.apis:
            if api.split('.')[0]==module:yield from self.function(api)

    def module_counts(self,module):
        logical=[name for name in self.counts if name.split('/')[0].split('.')[0]==module]
        return len(logical),sum(self.counts[name] for name in logical)

    def __iter__(self):
        for api in self.apis:yield from self.function(api)

    def __len__(self):return sum(self.counts.values())

    def __eq__(self,other):return all(a==b for a,b in zip_longest(self,other))


def _verified_cache(directory, signature=None):
    """Authenticate physical input files against a saved manifest.

    A matching signature identifies the harness version that indexed inputs;
    it does not prove a historical input was regenerated by that version.
    """
    directory=Path(directory)
    manifest=directory/'.cache.json'
    if not manifest.exists():return None
    index=json.loads(manifest.read_text())
    if index.get('format') not in (1,2):raise ValueError('Unsupported input cache manifest format')
    if signature is not None and index.get('recipe_sha256')!=signature:return None
    entries=index['files']
    if not isinstance(entries,dict):raise ValueError('Invalid case cache manifest')
    paths=case_paths(directory)
    if set(paths)!=set(entries):raise ValueError('Stale case CSV files: cache file set differs')
    for name,path in paths.items():
        if not isinstance(entries[name],dict) or type(entries[name].get('count')) is not int or entries[name]['count']<1:
            raise ValueError(f'Stale case CSV count: {name}')
        digest=hashlib.sha256()
        with path.open('rb') as stream:
            for data in iter(lambda:stream.read(1024*1024),b''):
                digest.update(data)
        if digest.hexdigest()!=entries[name]['sha256']:
            raise ValueError(f'Stale case CSV checksum: {name}')
    return CachedCaseSet(directory,paths,{name:entry['count'] for name,entry in entries.items()},
                         provenance=index.get('provenance'))


def cached_cases(directory, signature):
    """Load a manifest for the current harness signature, checking all file SHA-256s."""
    return _verified_cache(directory,signature)


def historical_cases(directory, *, expected_cases_sha256, measurements_directory,
                     expected_measurements_sha256):
    """Reuse historical cases on their own proven snapshot, regardless of new code.

    This verifies the previous manifest, canonical input digest, saved
    measurement digest, and the one-to-one function-file inventory. It never
    evaluates the current input generator or claims its inputs are equivalent.
    """
    cases=_verified_cache(directory)
    if cases is None:raise ValueError('Historical input cache manifest missing')
    if case_directory_digest(directory)!=expected_cases_sha256:
        raise ValueError('Historical case input digest mismatch')
    if directory_digest(measurements_directory)!=expected_measurements_sha256:
        raise ValueError('Historical measurement digest mismatch')
    measured={path.relative_to(measurements_directory).as_posix().removesuffix('.gz')
              for path in csv_paths(measurements_directory)}
    if measured!=set(cases.paths) or len(measured)!=len(csv_paths(measurements_directory)):
        raise ValueError('Historical measurement files differ from case inputs')
    return cases


class ExtendedCaseSet:
    """View verified historical inputs and separately generated new API cases."""
    def __init__(self, historical, new_cases):
        self.historical=historical
        added=defaultdict(list)
        identifiers=set()
        for case in new_cases:
            api=case['api'];identifier=case['id']
            if identifier in identifiers or not identifier.startswith(api+'/'):
                raise ValueError(f'Duplicate or invalid extension ID: {identifier}')
            identifiers.add(identifier)
            added[api].append(case)
        if set(added)&set(historical.apis):
            raise ValueError('Extension cannot change a historical function')
        self.added={api:sorted(batch,key=lambda case:case['id']) for api,batch in added.items()}
        self.apis=sorted(set(historical.apis)|set(self.added))

    def function(self,api):
        return self.added[api] if api in self.added else self.historical.function(api)

    def for_module(self,module):
        for api in self.apis:
            if api.split('.')[0]==module:yield from self.function(api)

    def module_counts(self,module):
        previous_names,previous_count=self.historical.module_counts(module)
        added=[batch for api,batch in self.added.items() if api.split('.')[0]==module]
        return previous_names+len(added),previous_count+sum(map(len,added))

    def __iter__(self):
        for api in self.apis:yield from self.function(api)

    def __len__(self):return len(self.historical)+sum(map(len,self.added.values()))
