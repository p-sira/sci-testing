"""Reuse pure public-API dispatch blocks from the pinned Sci fixture suites.

Exact markers deliberately fail when upstream test structure changes. Every
extracted block compiles as Rust and is checked against its paired SciPy oracle.
"""
from .rust_source import formatted
from .api_registry import SCI

from . import ROOT
SPECS={
    'fft':('fft_extended','        let re = vector(c[2]);','        assert_eq!(got_shape', 'got.into_iter().flat_map(|z| [z.re,z.im]).collect()'),
    'periodic':('fft_periodic','        let re = vector(c[2]);','        assert_eq!(vector(e[1])', 'got'),
    'cluster':('cluster','        let z = matrix(c[2]);','        let want = vector(e[3]);', 'got.into_iter().flatten().collect()'),
    'spatial':('geometry','        let (u, v, w) = (','        let (rows, cols):', 'actual.into_iter().flatten().collect()'),
    'optimize':('optimize_helpers','        let x = vector(c[2]);','        assert_eq!(got.len()', 'got.into_iter().flatten().collect()'),
    'differentiate':('differentiation','        let point = numbers(fields[2]);','        let expected: Vec<_> = common::fields(expected);', 'actual.into_iter().flatten().collect()'),
}


def generated():
    modules=[]
    for module,(filename,start,end,result) in SPECS.items():
        text=(SCI/f'tests/{filename}.rs').read_text()
        prefix=text.split('#[test]',1)[0].replace('mod common;', 'use crate::common;').replace('//!','//')
        begin=text.index(start);finish=text.index(end,begin)
        block=text[begin:finish].replace('let (got, got_shape)', 'let (got, _got_shape)')
        if module=='periodic':
            block=block.replace('let got = match c[1]', 'match c[1]').rstrip().removesuffix(';')
            result=''
        # The vector-alias is part of the numerical payload in the periodic suite.
        body=f'#[allow(dead_code, unused_imports)]\npub mod {module} {{\n{prefix}\npub fn run(c: &[&str]) -> Vec<f64> {{\n{('let fields=c;' if module=='differentiate' else '')}\n{('let input="generated case";' if module=='spatial' else '')}\n{block}\n{result}\n}}\n}}\n'
        modules.append(body)
    # Filter helpers occur between test functions; include that source intact.
    text=(SCI/'tests/filter.rs').read_text()
    start=text.index('        let a = &input[2..];')
    finish=text.index('        let expected = v(expected[1]);',start)
    modules.append('''#[allow(dead_code, unused_imports)]
pub mod filter {
include!(concat!(env!("OUT_DIR"), "/filter.rs"));
pub fn run(input: &[&str]) -> Vec<f64> {
'''+text[start:finish].replace('let actual = match input[1]', 'match input[1]').rstrip().removesuffix(';')+'\n}\n}\n')
    return '// Generated by generate_adapters.py; numerical dispatch is reused from pinned Sci tests.\n'+'\n'.join(modules)


if __name__=='__main__':
    (ROOT/'src/extracted.rs').write_text(formatted(generated()))
